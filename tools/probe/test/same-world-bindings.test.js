import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

// Native window bindings that a top-level let/const/class cannot shadow in a classic script.
const NATIVE_GLOBALS = ['location', 'document', 'window', 'self', 'top', 'parent', 'name', 'history', 'navigator', 'origin', 'status', 'length', 'event'];

async function worldGroups(dir, stripExports) {
  const manifest = JSON.parse(await readFile(`tools/probe/${dir}manifest.json`, 'utf8'));
  const groups = [];
  for (const [index, entry] of manifest.content_scripts.entries()) {
    const scripts = [];
    for (const file of entry.js) {
      // gpkg-svg.js is generated by the build (bundled from tools/gpkg-svg), so it only exists in dist/.
      const raw = await readFile(`tools/probe/${dir}${file}`, 'utf8').catch(error => { if (error.code === 'ENOENT' && stripExports && file === 'gpkg-svg.js') return null; throw error; });
      if (raw === null) continue;
      scripts.push({ file, code: stripExports ? raw.replace(/^export /gm, '') : raw });
    }
    groups.push({ label: `${entry.world || 'ISOLATED'}#${index}`, scripts });
  }
  return groups;
}

// A native global the page exposes as a non-configurable own property, like window.location.
function nativeContext() {
  const context = vm.createContext({});
  for (const name of NATIVE_GLOBALS) {
    vm.runInContext(`Object.defineProperty(globalThis, ${JSON.stringify(name)}, { value: undefined, configurable: false, writable: true });`, context);
  }
  return context;
}

for (const [dir, stripExports] of [['dist/', false], ['', true]]) {
  test(`content scripts of each world parse and load together (${dir || 'source'})`, async () => {
    for (const { label, scripts } of await worldGroups(dir, stripExports)) {
      assert.doesNotThrow(() => new vm.Script(scripts.map(s => s.code).join('\n;\n')), `${label} concatenation`);
      const context = nativeContext();
      for (const { file, code } of scripts) {
        assert.doesNotThrow(() => vm.runInContext(code, context, { filename: file }), `${label} ${file}`);
      }
    }
  });
}
